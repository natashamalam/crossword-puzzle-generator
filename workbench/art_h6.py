    c.L([(0, 66), (20, 62), (40, 68), (60, 62), (80, 68), (100, 64)], 1.4, G4, smooth=True)
    c.P([(20, 78), (26, 62), (50, 54), (74, 62), (82, 78)], f=G1, smooth=True, w=1.8)
    c.L([(50, 58), (46, 34), (52, 16)], 3.6, G5, smooth=True)
    for dx, dy in ((-22, 6), (-14, -8), (14, -8), (22, 6), (0, -12)):
        c.P([(52, 16), (52 + dx * .6, 10 + dy * .6), (52 + dx, 18 + dy)], f=G3, smooth=True, w=1.4)
    c.E(88, 16, 7, 7, f=W, w=1.6)

