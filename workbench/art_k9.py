    c.E(30, 46, 5, 3.4, f=W, o=None); c.dot(31, 46, 1.4, K)
    c.P([(52, 38), (60, 12), (66, 38)], f=K, w=1.6)
    c.P([(44, 70), (36, 88), (56, 74)], f=K, w=1.6)
    c.L([(0, 84), (14, 80), (28, 84), (44, 80), (60, 84), (78, 80), (100, 84)], 1.6, G4, smooth=True)
